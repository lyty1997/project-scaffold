// Actions from official GitHub organizations may use tags; other actions require a 40-character SHA.
const TRUSTED_ACTION_OWNERS = new Set(["actions", "github"]);
const LOOSE_SECRET_REFERENCE = /\$\{\{secrets\./;
const BRACKET_SECRET_REFERENCE = /\$\{\{\s*secrets\s*\[/;

function checkActionRef(uses, where, errors) {
  const [owner] = uses.split("/");
  if (TRUSTED_ACTION_OWNERS.has(owner)) return;
  if (!/@[0-9a-f]{40}$/.test(uses)) {
    errors.push(`${where}: third-party action \`${uses}\` must pin a 40-character SHA to control supply-chain risk; use owner/repo@<sha>`);
  }
}

// check-secrets.mjs intentionally flags `${{secrets.X}}` (without spaces) and
// quoted references. Enforce the one compliant form here rather than weakening
// the scanner and its protection of real credentials.
function checkSecretStyle(text, where, errors) {
  if (LOOSE_SECRET_REFERENCE.test(text)) {
    errors.push(`${where}: secret references must use \${{ secrets.NAME }} with spaces inside the braces; other forms are flagged by this repository's secret scanner`);
  }
  for (const match of text.matchAll(/["']\$\{\{\s*secrets\./g)) {
    errors.push(`${where}: do not quote secret references (offset ${match.index}); quoted references are flagged by this repository's secret scanner`);
  }
  if (BRACKET_SECRET_REFERENCE.test(text)) {
    errors.push(`${where}: bracket notation is not allowed for secrets; use statically auditable \${{ secrets.NAME }}`);
  }
}

function collectSecretNames(text, into) {
  for (const expression of text.matchAll(/\$\{\{([\s\S]*?)\}\}/g)) {
    for (const match of expression[1].matchAll(
      /\bsecrets\.([A-Za-z_][A-Za-z0-9_]*)\b/g,
    )) {
      into.add(match[1]);
    }
  }
}

